@EVALUATORS.register_module()
class ScalarEvaluator:
    """Aggregate scalar_stats from model outputs for validation."""
    def __init__(self, keys: List[str] = None, print_summary: bool = True) -> None:
        self.keys = set(keys) if keys else None
        self.print_summary = print_summary
        self.metrics = []

    @staticmethod
    def _to_float(value):
        if isinstance(value, torch.Tensor):
            return value.detach().mean().item()
        if isinstance(value, np.ndarray):
            return float(np.mean(value))
        if isinstance(value, (int, float)):
            return float(value)
        return None

    def evaluate(self, output: dotdict, batch: dotdict, **kwargs):
        scalar_stats = getattr(output, "scalar_stats", None)
        metrics = dotdict()
        if scalar_stats:
            for key, value in scalar_stats.items():
                if self.keys is not None and key not in self.keys:
                    continue
                val = self._to_float(value)
                if val is None:
                    continue
                metrics[key] = val

        if not metrics and hasattr(output, "loss"):
            val = self._to_float(output.loss)
            if val is not None:
                metrics.loss = val

        if len(metrics):
            self.metrics.append(metrics)

        return metrics

    def synchronize_metrics(self, max_size=None):
        if not get_distributed() or get_world_size() == 1:
            return
        try:
            rank_metrics = [None] * get_world_size()
            dist.all_gather_object(rank_metrics, self.metrics)
            if not get_rank():
                sync_metrics = []
                for i in range(len(rank_metrics[0])):
                    for metrics in rank_metrics:
                        sync_metrics.append(metrics[i])
                if max_size is not None and len(sync_metrics) > max_size:
                    log(f"Truncating metrics to {max_size} from {len(sync_metrics)}")
                    sync_metrics = sync_metrics[:max_size]
                self.metrics = sync_metrics
            else:
                self.metrics.clear()
        except Exception as e:
            log(red(f"Error during metrics synchronization: {e}"))
            log(yellow("Keeping original metrics due to synchronization error"))

    def summarize(self):
        summary = dotdict()
        if len(self.metrics):
            keys = sorted({k for m in self.metrics for k in m.keys()})
            for key in keys:
                values = [m[key] for m in self.metrics if key in m]
                if not values:
                    continue
                summary[f'{key}_mean'] = float(np.mean(values))
                summary[f'{key}_std'] = float(np.std(values))

        if len(summary) and self.print_summary:
            log(summary)

        if len(self.metrics):
            self.metrics.clear()
        return summary
